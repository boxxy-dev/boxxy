use crate::action::{ActionScope, ShortcutCategory, ShortcutId};

/// Static metadata and default bindings for a single `ShortcutId`.
#[derive(Clone, Copy, Debug)]
pub struct ActionSpec {
    pub id: ShortcutId,
    pub category: ShortcutCategory,
    pub scope: ActionScope,
    pub title: &'static str,
    pub action_name: &'static str,
    /// User-visible default shortcut strings (human format). Empty slice means unbound by default.
    pub default_triggers: &'static [&'static str],
    /// Secondary hardware/layout fallback keysyms automatically attached while the default
    /// primary trigger remains bound (e.g. Numpad `+`/`-`/`0`, `Ctrl+Equal` on US keyboards).
    pub implicit_aliases: &'static [&'static str],
    /// Additional search terms matched in Preferences -> Shortcuts and Command Palette.
    pub keywords: &'static [&'static str],
}

